// Generates lib/core/theme/tokens.g.dart from the web's design tokens.
//
// The web keeps every raw design value in tes-taker `frontend/design/tokens.json`
// (docs/ui/design-system.md). This app keeps a copy in tool/tokens.json so builds
// and tests do not need the other repository.
//
//   dart run tool/import_tokens.dart                     # regenerate from tool/tokens.json
//   dart run tool/import_tokens.dart <path/tokens.json>  # copy a newer file first, then regenerate
//
// test/core/theme/tokens_test.dart fails when tokens.g.dart and tool/tokens.json disagree.
import 'dart:convert';
import 'dart:io';

const _snapshot = 'tool/tokens.json';
const _output = 'lib/core/theme/tokens.g.dart';

void main(List<String> args) {
  if (args.isNotEmpty) {
    File(args.first).copySync(_snapshot);
    stdout.writeln('Copied ${args.first} to $_snapshot');
  }
  final tokens =
      jsonDecode(File(_snapshot).readAsStringSync()) as Map<String, dynamic>;
  File(_output).writeAsStringSync(generate(tokens));
  final format = Process.runSync('dart', ['format', _output], runInShell: true);
  if (format.exitCode != 0) {
    stderr.writeln(format.stderr);
    exit(format.exitCode);
  }
  stdout.writeln('Wrote $_output');
}

String generate(Map<String, dynamic> tokens) {
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/import_tokens.dart from tool/tokens.json')
    ..writeln(
      '// (tes-taker frontend/design/tokens.json). Do not edit by hand.',
    )
    ..writeln()
    ..writeln("import 'package:flutter/animation.dart';")
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln()
    ..writeln('/// Raw design values from the web. Use them through the theme')
    ..writeln(
      '/// (`AppColors`, `AppText`, `AppRadius`, …), not directly in widgets.',
    )
    ..writeln('abstract final class Tokens {');

  final colors = tokens['color'] as Map<String, dynamic>;
  for (final MapEntry(:key, :value) in colors.entries) {
    final hex = ((value as Map<String, dynamic>)['value'] as String).substring(
      1,
    );
    b.writeln(
      '  static const Color ${_camel('color-$key')} = Color(0xFF${hex.toUpperCase()});',
    );
  }

  final fonts = tokens['font'] as Map<String, dynamic>;
  for (final MapEntry(:key, :value) in fonts.entries) {
    final families = ((value as Map<String, dynamic>)['value'] as List<dynamic>)
        .map((f) => "'$f'")
        .join(', ');
    b.writeln(
      '  static const List<String> ${_camel('font-$key')} = [$families];',
    );
  }

  final text = tokens['text'] as Map<String, dynamic>;
  for (final MapEntry(:key, :value) in text.entries) {
    final t = value as Map<String, dynamic>;
    b
      ..writeln(
        '  static const double ${_camel('text-$key-size')} = ${_px(t['size'] as String)};',
      )
      ..writeln(
        '  static const double ${_camel('text-$key-line-height')} = ${t['lineHeight']};',
      );
  }

  final lineHeight = tokens['lineHeight'] as Map<String, dynamic>;
  for (final MapEntry(:key, :value) in lineHeight.entries) {
    b.writeln(
      '  static const double ${_camel('line-height-$key')} = ${(value as Map<String, dynamic>)['value']};',
    );
  }

  final radius = tokens['radius'] as Map<String, dynamic>;
  for (final MapEntry(:key, :value) in radius.entries) {
    b.writeln(
      '  static const double ${_camel('radius-$key')} = ${_px((value as Map<String, dynamic>)['value'] as String)};',
    );
  }

  final shadow = tokens['shadow'] as Map<String, dynamic>;
  for (final MapEntry(:key, :value) in shadow.entries) {
    final css = (value as Map<String, dynamic>)['value'] as String;
    final shadows = _cssShadows(css).join(', ');
    b.writeln(
      '  static const List<BoxShadow> ${_camel('shadow-$key')} = [$shadows];',
    );
  }

  final motion = tokens['motion'] as Map<String, dynamic>;
  for (final MapEntry(:key, :value) in motion.entries) {
    final m = value as Map<String, dynamic>;
    final ms = int.parse((m['duration'] as String).replaceAll('ms', ''));
    b
      ..writeln(
        '  static const Duration ${_camel('motion-$key-duration')} = Duration(milliseconds: $ms);',
      )
      ..writeln(
        '  static const Cubic ${_camel('motion-$key-easing')} = ${_cubic(m['easing'] as String)};',
      );
  }

  final spacing = tokens['spacing'] as Map<String, dynamic>;
  final base = (spacing['base'] as Map<String, dynamic>)['value'] as String;
  b
    ..writeln('  static const double spacingBase = ${_px(base)};')
    ..writeln('}');
  return b.toString();
}

/// `color-primary-soft` → `colorPrimarySoft`.
String _camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

/// `12px` → `12`.
String _px(String value) => num.parse(value.replaceAll('px', '')).toString();

/// `cubic-bezier(0, 0, 0.2, 1)` → `Cubic(0, 0, 0.2, 1)`.
String _cubic(String css) {
  final args = RegExp(r'cubic-bezier\(([^)]*)\)').firstMatch(css)!.group(1)!;
  final n = args
      .split(',')
      .map((s) => num.parse(s.trim()).toDouble())
      .join(', ');
  return 'Cubic($n)';
}

/// `0 1px 2px rgba(16, 24, 40, 0.06), …` → BoxShadow constructors.
/// CSS: x y blur [spread] color. Flutter's blurRadius takes the CSS blur as is.
List<String> _cssShadows(String css) {
  final shadow = RegExp(
    r'(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?(?:\s+(-?[\d.]+)(?:px)?)?\s+rgba\(([^)]*)\)',
  );
  return shadow.allMatches(css).map((m) {
    final rgba = m.group(5)!.split(',').map((s) => s.trim()).toList();
    return 'BoxShadow('
        'offset: Offset(${num.parse(m.group(1)!).toDouble()}, ${num.parse(m.group(2)!).toDouble()}), '
        'blurRadius: ${num.parse(m.group(3)!).toDouble()}, '
        'spreadRadius: ${num.parse(m.group(4) ?? '0').toDouble()}, '
        'color: Color.fromRGBO(${rgba[0]}, ${rgba[1]}, ${rgba[2]}, ${rgba[3]}))';
  }).toList();
}
